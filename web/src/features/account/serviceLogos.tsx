/** Brand colors for the services drawn with their letters. */
const tints: Partial<Record<TrackingServiceName, string>> = {
  mdblist: '#3D5A80',
  publicmetadb: '#2F6F62',
  listenbrainz: '#353070',
}

/**
 * The 40 px tile at the start of a tracking service's row: its logo, else its letters on its
 * color. `muted` greys it, for a service the administrator has not set up.
 */
export function ServiceLogo({
  service,
  letters,
  muted = false,
}: {
  service: TrackingServiceName
  letters: string
  muted?: boolean
}) {
  const logo = logos[service]
  return (
    <span
      aria-hidden="true"
      style={{ backgroundColor: logo?.color ?? tints[service] }}
      className={cx(
        'inline-grid size-10 shrink-0 place-items-center rounded-row border border-white/10 text-[15px] font-semibold tracking-[-0.02em] text-white shadow-[0_6px_18px_-8px] shadow-black/50',
        muted && 'opacity-45 grayscale',
      )}
    >
      {logo ? (
        <svg viewBox="0 0 24 24" width={20} height={20} fill="currentColor">
          <path d={logo.path} />
        </svg>
      ) : (
        letters
      )}
    </span>
  )
}
